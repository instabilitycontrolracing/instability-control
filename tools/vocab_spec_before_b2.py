for p in range(1, 61): BLOCKS.append(("P", f"P{p}", f"P {words(p)}."))
for t in range(1, 100): BLOCKS.append(("gap", f"{t/10:.1f}", f"{words(t // 10)} point {words(t % 10)}."))
