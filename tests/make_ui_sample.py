"""Writes engineer/ui/coach_mock.js: sample data for the browser preview (no Python behind the page).
The numbers are real output of engineer/analysis.compare and engineer/coach.coach_traces on synthetic laps.
    python tests/make_ui_sample.py
"""
import json, math, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.dirname(HERE))
import numpy as np
import synth as S
from engineer import coach
from engineer.analysis import compare


class FakeSess:
    """Just enough of telemetry.Session for analysis.compare()."""
    def __init__(self, tr):
        self._tr = tr

    def trace(self, n=None, step=1.0):
        return self._tr

    def find_corners(self):
        return S.corners_meta()


def main():
    ref = S.to_trace(S.simulate(S.reference_params()))
    P = S.with_mistake("hesitation", S.with_mistake("throttle_late", S.with_mistake("brake_early", scale=0.5)))
    P = S.with_mistake("abrupt_release", P)
    me = S.to_trace(S.simulate(P))
    cmp = compare(FakeSess(me), 3, FakeSess(ref), 1, points=700)
    co = coach.coach_traces(me, ref, S.corners_meta(),
                            ref_info={"label": "CSV · Garage 61 export (sample)", "source": "csv", "time": round(float(ref["t"][-1]), 3), "position": True},
                            lap_info={"n": 3, "time": round(float(me["t"][-1]), 3)}, extra={"car": "BMW M4 GT3", "track": "Synth Ring (preview)"})
    # a closed-looking map for the preview (the test track's geometry isn't a loop)
    d = np.arange(0, S.L, 1.0)
    k = S.curvature(d)
    k = k + (2 * math.pi - k.sum()) / len(d)
    th = np.cumsum(k)
    x, y = np.cumsum(np.cos(th)), np.cumsum(np.sin(th))
    x -= d / d[-1] * (x[-1] - x[0]); y -= d / d[-1] * (y[-1] - y[0])
    idx = np.linspace(0, len(d) - 1, 900).astype(int)
    laps = [{"n": 1, "time": round(float(ref["t"][-1]) + 0.9, 3), "complete": True, "valid": True, "pit": False},
            {"n": 2, "time": round(float(ref["t"][-1]) + 0.4, 3), "complete": True, "valid": True, "pit": False},
            {"n": 3, "time": round(float(me["t"][-1]), 3), "complete": True, "valid": True, "pit": False}]
    fmt = lambda t: f"{int(t // 60)}:{t % 60:06.3f}"
    open_ = {"sid": "preview", "theme": None, "theory": None, "notes": [], "car": "BMW M4 GT3", "track": "Synth Ring (preview)",
             "laps": laps, "best_n": 2, "map": {"x": x[idx].round(1).tolist(), "y": y[idx].round(1).tolist(), "d": d[idx].tolist()},
             "corners": S.corners_meta(), "track_len": S.L,
             "refs": [{"key": "best", "label": f"Best lap  ·  {fmt(laps[1]['time'])}"}] +
                     [{"key": f"lap:{L['n']}", "label": f"Lap {L['n']}  ·  {fmt(L['time'])}"} for L in laps]}
    g61 = {"ok": True, "only_mine": True, "laps": [{"id": "preview1", "time": laps[1]["time"], "driver": "You (preview)", "telemetry": True, "date": "2026-10-20"}],
           "note": "Garage 61 only gives this token your own (and teammates') laps. For an alien lap: open it on garage61.net, export the telemetry CSV, then use 'CSV file'."}
    data = {"sessions": [{"id": "preview", "label": "Synth Ring (preview)  ·  BMW M4 GT3  ·  2026-10-24 10:00"}], "open": open_,
            "compare": cmp, "coach": co, "g61": g61, "ref_label": f"Coach ref  ·  CSV · Garage 61 export (sample)  ·  {fmt(float(ref['t'][-1]))}"}
    out = os.path.join(os.path.dirname(HERE), "engineer", "ui", "coach_mock.js")
    with open(out, "w", encoding="utf-8") as f:
        f.write("/* Browser-preview sample for the driving coach (generated by tests/make_ui_sample.py from synthetic laps).\n"
                "   Only used when there is no Python behind the page. coach (2026-10-24) */\n")
        f.write("window.COACH_SAMPLE = " + json.dumps(data, separators=(",", ":")) + ";\n")
    print("wrote", out, os.path.getsize(out), "bytes")


if __name__ == "__main__":
    main()
